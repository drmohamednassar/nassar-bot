export default async function (sock, m, from, args, config) {
  try {
    const categoryInput = args[0]?.toLowerCase().trim();
    let selectedList = [];
    let title = "ذكر عشوائي";

    if (categoryInput === "صباح" || categoryInput === "الصباح") {
      selectedList = azkarData.صباح;
      title = "أذكار الصباح";
    } else if (categoryInput === "مساء" || categoryInput === "المساء") {
      selectedList = azkarData.مساء;
      title = "أذكار المساء";
    } else if (categoryInput === "نوم" || categoryInput === "النوم") {
      selectedList = azkarData.نوم;
      title = "أذكار النوم";
    } else {
      // دمج جميع الأقسام لاختيار ذكر عشوائي
      selectedList = [
        ...azkarData.صباح,
        ...azkarData.مساء,
        ...azkarData.نوم,
        ...azkarData.عام
      ];
    }

    const item = selectedList[Math.floor(Math.random() * selectedList.length)];

    const response = 
      `📿 *[ ${title} ]* 📿\n\n` +
      `📜 *الذِّكْر:*\n"${item.text}"\n\n` +
      `🔢 *التكرار:* ${item.repeat} ${item.repeat > 1 ? "مرات" : "مرة"}\n` +
      `✨ *الفضل:* ${item.virtue}\n\n` +
      `💡 _يمكنك طلب تصنيف محدد:_\n` +
      `*.azkar صباح* | *.azkar مساء* | *.azkar نوم*`;

    await sock.sendMessage(from, { text: response }, { quoted: m });

  } catch (error) {
    console.error("Azkar Error:", error);
    await sock.sendMessage(from, { text: "❌ حدث خطأ أثناء عرض الذكر." }, { quoted: m });
  }
}
