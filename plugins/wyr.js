export default async function (sock, m, from) {
  const questions = [
    "لو خيروك: تسافر للمستقبل تشوف حياتك، ولا ترجع للماضي تصحح غلطة واحدة؟",
    "لو خيروك: تعيش في جزيرة معزولة مع إنترنت غير محدود، ولا في قصر فخم بدون أي تكنولوجيا؟",
    "لو خيروك: تقدر تقرأ أفكار اللي قدامك، ولا تختفي تماماً وقت ما تحب؟",
    "لو خيروك: تتكلم كل لغات العالم بطلاقة، ولا تكون خبير في كل مجالات البرمجة؟",
    "لو خيروك: تنام 3 ساعات بس وتصحى بكامل طاقتك، ولا تاكل اللي تحبه بدون ما يزيد وزنك؟"
  ];

  const randomQ = questions[Math.floor(Math.random() * questions.length)];
  await sock.sendMessage(from, { text: `🤔 *تحدي لو خيروك:*\n\n${randomQ}` }, { quoted: m });
}
